# ---------------------------------------------------------------- frame tap


def test_pipeline_frame_tap_sees_tracks_and_candidates(tmp_path, monkeypatch):
    """The preview hook receives every frame; on the simulate scenario it must
    observe live tracks and at least one rule firing, and a raising tap must
    disable itself without killing the pipeline."""
    from sentinel_edge.config import EdgeSettings, PipelineDefaults
    from sentinel_edge.main import CameraPipeline, Supervisor, _synthetic_frames

    monkeypatch.chdir(tmp_path)
    settings = EdgeSettings(data_dir=tmp_path / "data")
    defaults = PipelineDefaults(backend="mock", motion_min_fraction=0.0005,
                                min_object_px=8, clip_pre_s=0.5, clip_post_s=0.2,
                                rule_cooldown_s=5.0)
    config = DeviceConfig.model_validate_json(CONFIG.read_text(encoding="utf-8"))

    seen = {"frames": 0, "tracks": 0, "cands": 0}

    def tap(camera, frame, tracks, candidates, line_counts):
        seen["frames"] += 1
        seen["tracks"] += len(tracks)
        seen["cands"] += len(candidates)
        if seen["frames"] == 1:
            raise RuntimeError("tap blew up")  # must be contained + disabled

    async def go():
        sup = Supervisor(settings, defaults, frame_tap=tap)
        await sup.inference.start()
        cam = config.cameras[0]
        pipeline = CameraPipeline(
            cam, defaults, sup.inference, sup.queue, sup.spool, sup.health, sup,
            frame_source=_synthetic_frames(6.0, 10, (640, 360)), on_frame=tap)

        async def patch_encoders():
            while pipeline.recorder is None:
                await asyncio.sleep(0.01)
            async def fake(frames, fps, out_path):
                out_path.write_bytes(b"x")
            async def fake_t(frame, out_path):
                out_path.write_bytes(b"x")
            pipeline.recorder.encoder = fake
            pipeline.recorder.thumb_encoder = fake_t

        await asyncio.gather(pipeline.run(), patch_encoders())
        await sup.inference.stop()
        sup.queue.close()
        return pipeline

    pipeline = asyncio.run(go())
    # first call raised -> tap disabled on that pipeline
    assert pipeline.on_frame is None
    assert seen["frames"] == 1


